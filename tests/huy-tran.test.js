import { test, expect } from "vitest";
import { setup } from "./helpers/env.js";

test("hủy trận phải xác nhận, hoàn tác khôi phục mọi trận đã hủy/xóa", async () => {
  const e = setup({ pin: true });
  await e.boot();
  e.input("bulk", "Tuấn\nHà | nữ\nMinh\nLan | nữ\nKhoa\nVy | nữ\nBình\nMai | nữ"); await e.click("add");
  await e.tab("san"); await e.ok("start");
  await e.click("courts", { d: "1" }).catch(() => {});
  await e.click("gen");
  const playing = () => e.docs("matches/", x => x.status === "playing");
  const n0 = playing().length;
  expect(n0).toBeGreaterThan(0);
  const [id] = playing()[0];
  await e.click("cancel", { id });
  expect(playing().length).toBe(n0);
  expect(e.CF()).toContain("Hủy trận");
  expect(e.CF()).toContain("Bốn người quay lại hàng chờ");
  await e.click("cfmx");
  expect(e.CF()).toBe("");
  expect(playing().length).toBe(n0);
  await e.ok("cancel", { id });
  expect(playing().length).toBe(n0 - 1);
  expect(e.T()).toContain("1 thao tác hủy/xóa có thể hoàn tác");
  await e.click("undoopen");
  expect(e.T()).toContain("Hủy trận · Sân");
  await e.click("undoone", { id });
  expect(playing().length).toBe(n0 - 1);
  await e.click("undoone", { id });
  expect(playing().length).toBe(n0);
  expect(e.store.get("matches/" + id)).toBeTruthy();
  expect(e.V()).not.toContain('data-act="undoopen"');
});

test("thanh 3 bước bấm chuyển qua lại, hàng chờ chia nam nữ, thêm người ngay trong điểm danh", async () => {
  const e = setup({ pin: true });
  await e.boot();
  e.input("bulk", "Tuấn\nHà | nữ\nMinh\nLan | nữ\nKhoa\nVy | nữ"); await e.click("add");
  await e.tab("san");
  expect(e.V()).toContain('data-act="step"');
  await e.click("step", { v: "live" });
  expect(e.T()).toContain("Giải đấu #1 · chuẩn bị");
  await e.ok("start"); await e.click("gen");
  await e.click("lseg", { v: "cho" });
  expect(e.T()).toContain("Hàng chờ (2)");
  expect(e.V()).toContain('class="qgrid"');
  expect(e.T()).toMatch(/Nam · 1.+Nữ · 1/);
  await e.click("step", { v: "prep" });
  expect(e.T()).toContain("Về trang Đang đánh");
  expect(e.V()).toContain("ac on busy");
  await e.click("attadd");
  expect(e.V()).toContain('id="bulk"');
  e.input("bulk", "Bình"); await e.click("add");
  expect(e.docs("players/", p => p.name === "Bình" && p.active).length).toBe(1);
  expect(e.url).not.toContain("nguoi");
  await e.click("step", { v: "live" });
  await e.click("lseg", { v: "san" });
  expect(e.T()).toContain("Sân đang đánh");
  await e.click("step", { v: "chot" });
  expect(e.T()).toContain("Chốt giải đấu #1");
});
